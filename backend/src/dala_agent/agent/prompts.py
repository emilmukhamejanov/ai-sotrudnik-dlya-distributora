class ActionDraft(BaseModel):
    """Действие в Битрикс24, о котором просит пользователь."""

    kind: Literal["create_task", "create_deal", "unsupported"]
    title: str = Field(description="Короткое название задачи или сделки")
    description: str = Field("", description="Подробности из сообщения пользователя")
    responsible_surname: str | None = Field(
        None, description="Фамилия ответственного в именительном падеже: «Иванову» → «Иванов»"
    )
    responsible_first_name: str | None = Field(None, description="Имя ответственного в именительном падеже")
    deadline: date | None = Field(None, description="Срок (ISO-дата), если назван")
    amount_kzt: float | None = Field(None, description="Сумма сделки в тенге, если названа")
    client_name: str | None = Field(None, description="Клиент, если назван")
    missing: str | None = Field(None, description="Вопрос пользователю, если без него действие не выполнить")


