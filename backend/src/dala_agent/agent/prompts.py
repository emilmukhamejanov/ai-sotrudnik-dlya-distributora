from pydantic import BaseModel, Field


class RouteDecision(BaseModel):
    """Куда направить сообщение пользователя."""

    route: Literal["data", "docs", "data_and_docs", "action", "human", "smalltalk"]
    language: Literal["ru", "kk"] = Field(description="Язык сообщения пользователя")
    reason: str = Field(description="Коротко, почему выбран этот маршрут")
    search_query: str = Field(
        "",
        description=(
            "Только для docs и data_and_docs: 4–10 ключевых слов для поиска по регламентам в начальной форме, "
            "с синонимами в языке документов (например, «просроченные партии» → «истёкший срок годности "
            "карантин отгрузка»). Для остальных маршрутов — пустая строка"
        ),
    )


