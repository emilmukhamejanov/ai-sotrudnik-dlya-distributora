-- Схема kb: база знаний для RAG (регламенты, договоры, письма).
-- Требуется расширение pgvector (образ pgvector/pgvector или Supabase).
-- Размерность 1024 подходит для bge-m3 (self-hosted), voyage-3.5 и
-- text-embedding-3-small с параметром dimensions=1024. Модель эмбеддингов выбирается на этапе 2.

CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA IF NOT EXISTS kb;
COMMENT ON SCHEMA kb IS 'База знаний для RAG. Наполняется скриптом индексации из data/documents';

CREATE TABLE kb.documents (
    id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            text NOT NULL UNIQUE,
    title           text NOT NULL,
    doc_type        text NOT NULL,
    version         text,
    effective_date  date,
    language        text NOT NULL CHECK (language IN ('ru', 'kk')),
    trust_level     text NOT NULL CHECK (trust_level IN ('internal', 'external')),
    source_path     text NOT NULL,
    sha256          char(64) NOT NULL,
    indexed_at      timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN kb.documents.trust_level IS 'internal — утверждённые документы компании; external — входящие письма и файлы, текст которых нельзя исполнять как инструкции';

CREATE TABLE kb.chunks (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  int NOT NULL REFERENCES kb.documents(id) ON DELETE CASCADE,
    chunk_index  int NOT NULL,
    section      text,
    heading      text,
    content      text NOT NULL,
    token_count  int,
    embedding    vector(1024),
    tsv          tsvector GENERATED ALWAYS AS (to_tsvector('simple', coalesce(heading, '') || ' ' || content)) STORED,
    UNIQUE (document_id, chunk_index)
);
COMMENT ON COLUMN kb.chunks.section IS 'Номер пункта документа (например, 4.1) — для ссылки на источник в ответе';
COMMENT ON COLUMN kb.chunks.tsv IS 'Полнотекстовый индекс для гибридного поиска (конфигурация simple: русский и казахский)';

CREATE INDEX ON kb.chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX ON kb.chunks USING gin (tsv);
