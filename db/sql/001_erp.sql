-- Схема erp: «сырая» демо-выгрузка из 1С:Управление торговлей.
-- ВСЕ ДАННЫЕ СИНТЕТИЧЕСКИЕ (см. erp.export_info).
-- Суммы в тенге (₸) с НДС. НДС: 12% до 31.12.2025, 16% с 01.01.2026 (новый Налоговый кодекс РК).

CREATE SCHEMA IF NOT EXISTS erp;
COMMENT ON SCHEMA erp IS 'Демо-выгрузка из 1С (синтетические данные). Содержит ПДн — агенту недоступна, он работает через схему analytics.';

CREATE TABLE erp.export_info (
    export_date   date PRIMARY KEY,
    source        text NOT NULL,
    company       text NOT NULL,
    period_start  date NOT NULL,
    period_end    date NOT NULL,
    note          text NOT NULL
);
COMMENT ON TABLE erp.export_info IS 'Паспорт выгрузки: дата, период, пометка о синтетических данных';

CREATE TABLE erp.warehouses (
    id       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     text NOT NULL UNIQUE,
    name     text NOT NULL,
    city     text NOT NULL,
    address  text NOT NULL
);
COMMENT ON TABLE erp.warehouses IS 'Склады';

CREATE TABLE erp.products (
    id                  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 text NOT NULL UNIQUE,
    name                text NOT NULL,
    category            text NOT NULL,
    brand               text NOT NULL,
    supplier            text NOT NULL,
    unit                text NOT NULL,
    box_qty             int  NOT NULL CHECK (box_qty > 0),
    price_kzt           numeric(14,2) NOT NULL,
    purchase_price_kzt  numeric(14,2) NOT NULL,
    shelf_life_days     int  NOT NULL,
    is_active           boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE erp.products IS 'Номенклатура';
COMMENT ON COLUMN erp.products.sku IS 'Артикул: НАП напитки, МОЛ молочка, БАК бакалея, ЧАЙ чай и кофе, КОН кондитерка, КНС консервация';
COMMENT ON COLUMN erp.products.box_qty IS 'Единиц в коробе (кратность отгрузки)';
COMMENT ON COLUMN erp.products.price_kzt IS 'Действующая оптовая цена за единицу с НДС, ₸ (цены 2025 года были ниже, см. sales_lines.price_kzt)';
COMMENT ON COLUMN erp.products.purchase_price_kzt IS 'Действующая закупочная цена за единицу, ₸';

CREATE TABLE erp.managers (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       text NOT NULL UNIQUE,
    full_name  text NOT NULL,
    position   text NOT NULL,
    city       text NOT NULL,
    phone      text NOT NULL,
    email      text NOT NULL,
    hired_at   date NOT NULL
);
COMMENT ON TABLE erp.managers IS 'Сотрудники отдела продаж';
COMMENT ON COLUMN erp.managers.phone IS 'ПДн';

CREATE TABLE erp.clients (
    id                  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                text NOT NULL UNIQUE,
    name                text NOT NULL,
    legal_form          text NOT NULL CHECK (legal_form IN ('ТОО', 'ИП')),
    bin                 char(12),
    iin                 char(12),
    segment             text NOT NULL CHECK (segment IN ('Сеть', 'Опт', 'HoReCa', 'Розница')),
    city                text NOT NULL,
    address             text NOT NULL,
    contact_name        text NOT NULL,
    contact_phone       text NOT NULL,
    manager_id          int  NOT NULL REFERENCES erp.managers(id),
    warehouse_id        int  NOT NULL REFERENCES erp.warehouses(id),
    payment_terms_days  int  NOT NULL,
    credit_limit_kzt    numeric(14,2) NOT NULL,
    base_discount_pct   numeric(5,2)  NOT NULL,
    created_at          date NOT NULL,
    is_active           boolean NOT NULL,
    shipment_blocked    boolean NOT NULL,
    CHECK ((legal_form = 'ТОО' AND bin IS NOT NULL AND iin IS NULL)
        OR (legal_form = 'ИП'  AND iin IS NOT NULL AND bin IS NULL))
);
COMMENT ON TABLE erp.clients IS 'Контрагенты-покупатели';
COMMENT ON COLUMN erp.clients.iin IS 'ИИН индивидуального предпринимателя — ПДн (синтетический, с корректной контрольной цифрой)';
COMMENT ON COLUMN erp.clients.contact_name IS 'ПДн';
COMMENT ON COLUMN erp.clients.contact_phone IS 'ПДн';
COMMENT ON COLUMN erp.clients.payment_terms_days IS 'Отсрочка платежа, дней; 0 — предоплата';
COMMENT ON COLUMN erp.clients.shipment_blocked IS 'Отгрузки заблокированы (просрочка более 15 дней, кредитная политика п. 4.1)';

CREATE TABLE erp.sales_documents (
    id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_number        text NOT NULL UNIQUE,
    doc_date          date NOT NULL,
    doc_type          text NOT NULL CHECK (doc_type IN ('Реализация', 'Возврат')),
    is_posted         boolean NOT NULL,
    client_id         int NOT NULL REFERENCES erp.clients(id),
    manager_id        int NOT NULL REFERENCES erp.managers(id),
    warehouse_id      int NOT NULL REFERENCES erp.warehouses(id),
    base_document_id  int REFERENCES erp.sales_documents(id),
    amount_kzt        numeric(16,2) NOT NULL,
    vat_kzt           numeric(16,2) NOT NULL,
    comment           text
);
COMMENT ON TABLE erp.sales_documents IS 'Документы «Реализация товаров» и «Возврат товаров от клиента»';
COMMENT ON COLUMN erp.sales_documents.is_posted IS 'Проведён. Непроведённые документы (черновики) в отчётах не учитываются';
COMMENT ON COLUMN erp.sales_documents.base_document_id IS 'Для возврата — документ реализации-основание';
COMMENT ON COLUMN erp.sales_documents.amount_kzt IS 'Сумма документа с НДС, ₸ (всегда положительная; возврат уменьшает выручку)';

CREATE TABLE erp.sales_lines (
    id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   int NOT NULL REFERENCES erp.sales_documents(id),
    line_no       int NOT NULL,
    product_id    int NOT NULL REFERENCES erp.products(id),
    quantity      numeric(14,3) NOT NULL CHECK (quantity > 0),
    price_kzt     numeric(14,2) NOT NULL,
    discount_pct  numeric(5,2)  NOT NULL,
    amount_kzt    numeric(16,2) NOT NULL,
    vat_rate      int NOT NULL CHECK (vat_rate IN (12, 16)),
    vat_kzt       numeric(16,2) NOT NULL,
    cost_kzt      numeric(16,2) NOT NULL,
    UNIQUE (document_id, line_no)
);
COMMENT ON TABLE erp.sales_lines IS 'Строки документов продаж и возвратов';
COMMENT ON COLUMN erp.sales_lines.price_kzt IS 'Цена за единицу с НДС до скидки, ₸';
COMMENT ON COLUMN erp.sales_lines.amount_kzt IS 'Сумма строки с НДС после скидки, ₸';
COMMENT ON COLUMN erp.sales_lines.cost_kzt IS 'Себестоимость строки по закупочной цене, ₸';

CREATE TABLE erp.stock_balances (
    id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of_date       date NOT NULL,
    warehouse_id     int  NOT NULL REFERENCES erp.warehouses(id),
    product_id       int  NOT NULL REFERENCES erp.products(id),
    lot_number       text NOT NULL,
    production_date  date NOT NULL,
    expiry_date      date NOT NULL,
    quantity         numeric(14,3) NOT NULL CHECK (quantity >= 0),
    reserved_qty     numeric(14,3) NOT NULL DEFAULT 0 CHECK (reserved_qty >= 0)
);
COMMENT ON TABLE erp.stock_balances IS 'Остатки по партиям на дату выгрузки (позиции с нулевым остатком не выгружаются)';
COMMENT ON COLUMN erp.stock_balances.reserved_qty IS 'Зарезервировано под заказы';

CREATE TABLE erp.receivables (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of_date   date NOT NULL,
    client_id    int  NOT NULL REFERENCES erp.clients(id),
    document_id  int  NOT NULL REFERENCES erp.sales_documents(id),
    doc_date     date NOT NULL,
    due_date     date NOT NULL,
    amount_kzt   numeric(16,2) NOT NULL,
    paid_kzt     numeric(16,2) NOT NULL DEFAULT 0
);
COMMENT ON TABLE erp.receivables IS 'Ведомость открытых взаиморасчётов (дебиторка) на дату выгрузки: только неоплаченные и частично оплаченные реализации';

CREATE TABLE erp.sales_plans (
    id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id       int  NOT NULL REFERENCES erp.managers(id),
    month            date NOT NULL CHECK (extract(day FROM month) = 1),
    plan_amount_kzt  numeric(16,2) NOT NULL,
    UNIQUE (manager_id, month)
);
COMMENT ON TABLE erp.sales_plans IS 'План продаж по менеджерам на месяц, ₸ с НДС';

CREATE INDEX ON erp.sales_documents (doc_date);
CREATE INDEX ON erp.sales_documents (client_id);
CREATE INDEX ON erp.sales_documents (manager_id);
CREATE INDEX ON erp.sales_lines (product_id);
CREATE INDEX ON erp.stock_balances (warehouse_id, product_id);
CREATE INDEX ON erp.receivables (client_id);
